-- Drop and recreate student_applications table with full schema
DROP TABLE IF EXISTS student_applications;

CREATE TABLE student_applications (
    id INT AUTO_INCREMENT PRIMARY KEY,
    application_reference VARCHAR(50) UNIQUE,
    first_name VARCHAR(100),
    middle_names VARCHAR(100),
    last_name VARCHAR(100),
    email VARCHAR(255),
    contact_number VARCHAR(20),
    date_of_birth DATE,
    gender VARCHAR(20),
    nationality VARCHAR(100),
    address_line1 VARCHAR(255),
    address_line2 VARCHAR(255),
    town_city VARCHAR(100),
    postcode VARCHAR(20),
    country_of_residence VARCHAR(100),
    course_title VARCHAR(255),
    course_code VARCHAR(50),
    course_type VARCHAR(50),
    mode_of_study VARCHAR(50),
    intake_start_date DATE,
    entry_route VARCHAR(100),
    highest_qualification VARCHAR(100),
    institution_name VARCHAR(255),
    year_completed INT,
    english_proficiency VARCHAR(50),
    english_score VARCHAR(10),
    relevant_work_experience VARCHAR(255),
    has_disabilities_support_needs BOOLEAN DEFAULT FALSE,
    disability_support_details TEXT,
    consent_gdpr BOOLEAN DEFAULT TRUE,
    consent_data_sharing BOOLEAN DEFAULT TRUE,
    consent_marketing BOOLEAN DEFAULT FALSE,
    declaration_truth BOOLEAN DEFAULT FALSE,
    offer_accepted BOOLEAN DEFAULT FALSE,
    submitted_at DATETIME,
    passport_id_document VARCHAR(255),
    academic_certificates VARCHAR(255),
    academic_transcripts VARCHAR(255),
    english_certificate VARCHAR(255),
    student_contract VARCHAR(255),
    cv_resume VARCHAR(255),
    work_reference VARCHAR(255),
    proof_of_address VARCHAR(255),
    visa_immigration_document VARCHAR(255),
    statement_of_purpose_document VARCHAR(255),
    brp_card VARCHAR(255),
    residency_proof VARCHAR(255),
    application_status VARCHAR(50) DEFAULT 'submitted',
    is_deleted BOOLEAN DEFAULT FALSE,
    deleted_at DATETIME,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_email (email),
    INDEX idx_status (application_status),
    INDEX idx_course_code (course_code),
    INDEX idx_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

